function S = params()
% 2025 高教社杯数模 A 题「烟幕干扰弹的投放策略」共享参数与场景数据
% 符号与《烟幕干扰弹投放策略——整合优化建模.md》§1.1 一致（论文记号）
S.v_m     = 300;            % 导弹速度 m/s
S.vmin    = 70;             % 无人机速度下界 m/s
S.vmax    = 140;            % 无人机速度上界 m/s
S.v_sink  = 3;              % 云团下沉速度 m/s
S.g       = 9.8;            % 重力加速度 m/s^2
S.r       = 10;             % 云团有效半径 m
S.Ts      = 20;             % 单弹有效遮蔽时长上限 s
S.dt_min  = 1;              % 同机相邻投弹最小间隔 s

% 3 枚导弹初始位置 (t=0)
S.Pm0  = [20000     0  2000;
          19000   600  2100;
          18000  -600  1900];
% 5 架无人机初始位置 (t=0)
S.Pfy0 = [17800     0  1800;
          12000  1400  1400;
           6000 -3000   700;
          11000  2000  1800;
          13000 -2000  1300];

% 真目标圆柱 Ω = {x^2+(y-200)^2<=7^2, 0<=z<=10}
S.cy = 200;  S.cr = 7;  S.zc = [0 10];

% 遮蔽判定采样 (MD §3.4/§3.5)
S.n_single  = 300;                % 单弹判定: 每底面圆周采样点数
S.n_multi   = 50;                 % 多弹判定: 每层圆周采样点数
S.z_layers  = [0 2.5 5 7.5 10];   % 多弹判定: 5 个采样高度层

% 遮蔽时长计算 (MD §3.6)
S.eps_t   = 1e-5;                 % 二分法时间精度 s
S.scan_dt = 0.05;                 % 遮蔽区间粗扫步长 s (须小于最短遮蔽区间)

% 各导弹抵达假目标(原点)时刻
S.t_hit = sqrt(sum(S.Pm0.^2, 2)) / S.v_m;   % 3x1, 约 [67.0; 63.7; 60.4]
end
